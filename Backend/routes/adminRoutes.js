const router = require("express").Router();
const c = require("../controllers/adminController");
const { protect, authorize } = require("../middleware/auth");
router.use(protect, authorize("admin"));
router.get("/dashboard", c.dashboard);
router.get("/bookings", c.bookings);
router.get("/users", c.users);
router.get("/users/:id", c.user);
router.get("/users/:id/identity-document", c.identityDocument);
router.patch("/users/:id/identity-status", c.updateIdentityStatus);
router.get("/reports", c.reports);
router.get("/violations", c.violations);
module.exports = router;
